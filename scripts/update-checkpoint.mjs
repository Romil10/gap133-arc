// Recount Paid events up to a safe recent block and write lib/stats-checkpoint.mjs.
// Run locally or from the daily GitHub Action: node scripts/update-checkpoint.mjs
import { writeFileSync } from 'node:fs';
import { publicClient } from '../lib/core.mjs';
import { baseState, scan, stampRecent, serialise } from '../lib/stats.mjs';
import checkpoint from '../lib/stats-checkpoint.mjs';

const contract = process.env.CONTRACT_ADDRESS || checkpoint.contract;
const client = publicClient();
const state = baseState(contract);
const head = (await client.getBlockNumber()) - 5n; // stay a few blocks behind the tip
await scan(client, state, head);
await stampRecent(client, state);
const out = serialise(state);
writeFileSync(
  new URL('../lib/stats-checkpoint.mjs', import.meta.url),
  '// Generated by scripts/update-checkpoint.mjs. Totals of Paid events up to `block`.\n' +
    'export default ' + JSON.stringify(out, null, 2) + ';\n',
);
console.log(`checkpoint: ${out.count} paid queries, ${out.payers.length} wallets, through block ${out.block}`);
